"""
The project workload kit: the one v3 kit agy-sandbox generates. It carries the
project's Dockerfile (Dockerfile.agy, or the packaged default) with build_args as
kit args, and setup_scripts as its install hook. sbx builds it when the sandbox
is created; nothing here runs Docker.
"""
import hashlib
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Tuple

import yaml

from .config import AgyConfig
from .constants import (
    DEFAULT_DOCKERFILE_NAME,
    KIT_DESCRIPTOR_SYNTAX,
    KIT_SCHEMA_VERSION,
    LOCAL_DOCKERFILE_NAME,
    WORKLOAD_KIT_NAME,
)
from .errors import ConfigError
from . import paths

PACKAGED_DOCKERFILE = Path(__file__).resolve().parent / "docker" / DEFAULT_DOCKERFILE_NAME
_BASE_IMAGE_ARG = re.compile(r"^ARG\s+BASE_IMAGE\s*(=.*)?$", re.MULTILINE)
_DIRECTIVE = re.compile(r"^\s*#\s*(syntax|escape|check)\s*=", re.IGNORECASE)


@dataclass(frozen=True)
class WorkloadRef:
    dir: str
    fingerprint: str   # sha256 over the written descriptor and Dockerfile


@dataclass(frozen=True)
class Rendered:
    """The workload kit's two files as text, before or without writing them."""
    ref: WorkloadRef
    descriptor: str
    dockerfile: str


class _Dumper(yaml.SafeDumper):
    """Multi-line strings (hook scripts) as literal blocks so the descriptor stays readable."""


def _str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_presenter)


def project_dockerfile(cwd: Path) -> Tuple[Path, bool]:
    """The project's own Dockerfile.agy when present, else the packaged default."""
    local = Path(cwd) / LOCAL_DOCKERFILE_NAME
    if local.is_file():
        return local, True
    if not PACKAGED_DOCKERFILE.is_file():
        raise ConfigError(f"Packaged {DEFAULT_DOCKERFILE_NAME} is missing from the installation.")
    return PACKAGED_DOCKERFILE, False


def render_descriptor(config: AgyConfig, *, include_setup: bool = True) -> dict:
    args = {"BASE_IMAGE": {"default": config.base_image, "buildArg": "BASE_IMAGE"}}
    for key, value in config.build_args.items():
        args[key] = {"default": str(value), "buildArg": key}
    descriptor = {
        "schemaVersion": KIT_SCHEMA_VERSION,
        "kind": "workload",
        "displayName": f"{config.project_name} (agy-sandbox workload)",
        "description": f"Generated by agy-sandbox from agy.yaml and {LOCAL_DOCKERFILE_NAME}. Do not edit.",
        "args": args,
        "capabilities": [{"type": "com.docker.sandbox/sbx@1"}],
    }
    # A recreate builds from a snapshot that already holds everything setup_scripts produced
    # (fetched deps, installed tools), so re-running them is redundant and, when the session
    # user was converted root->agent, broken: the install hook runs as agent before the old
    # root home (with its per-user toolchain state) has been migrated. include_setup=False
    # drops the hook for those snapshot creates; the startup hooks are kept.
    if config.setup_scripts and include_setup:
        script = "set -e\ncd \"${WORKSPACE_DIR:-$HOME}\"\n" + "\n".join(config.setup_scripts) + "\n"
        descriptor["capabilities"].append({
            "type": "com.docker.sandbox/lifecycle@1",
            "config": {
                "install": [{
                    # A login shell: hooks get only PATH and HOME from sbx, and /etc/profile.d
                    # carries the toolchain environment the Dockerfile set (see Dockerfile.default).
                    "command": ["bash", "-lc", script],
                    "user": "agent",
                    "env": ["WORKSPACE_DIR"],
                    "description": "agy.yaml setup_scripts",
                }]
            },
        })
    return descriptor


def render_dockerfile(source_text: str, base_image: str) -> str:
    """
    The Dockerfile verbatim, with `ARG BASE_IMAGE` defaulting to the configured base. When
    the file declares no such ARG, one is inserted after any leading parser directives
    (`# syntax=`, `# escape=`), which BuildKit only honours on the first lines.
    """
    line = f"ARG BASE_IMAGE={base_image}"
    if _BASE_IMAGE_ARG.search(source_text):
        return _BASE_IMAGE_ARG.sub(line, source_text, count=1)
    lines = source_text.splitlines(keepends=True)
    index = 0
    while index < len(lines) and _DIRECTIVE.match(lines[index]):
        index += 1
    lines.insert(index, line + "\n")
    return "".join(lines)


def descriptor_text(config: AgyConfig, *, include_setup: bool = True) -> str:
    body = yaml.dump(render_descriptor(config, include_setup=include_setup), Dumper=_Dumper, sort_keys=False, width=1000)
    return f"{KIT_DESCRIPTOR_SYNTAX}\n{body}"


def fingerprint(descriptor: str, dockerfile: str) -> str:
    digest = hashlib.sha256()
    digest.update(descriptor.encode("utf-8"))
    digest.update(b"\0")
    digest.update(dockerfile.encode("utf-8"))
    return f"sha256:{digest.hexdigest()}"


def render(config: AgyConfig, cwd: Path) -> Rendered:
    """What the workload kit for this config would contain; touches nothing on disk."""
    source, _ = project_dockerfile(cwd)
    dockerfile = render_dockerfile(source.read_text(encoding="utf-8"), config.base_image)
    descriptor = descriptor_text(config)
    kit_dir = paths.workload_dir(config.sandbox_name)
    return Rendered(WorkloadRef(dir=str(kit_dir), fingerprint=fingerprint(descriptor, dockerfile)), descriptor, dockerfile)


def write(config: AgyConfig, cwd: Path) -> WorkloadRef:
    """Writes (or refreshes) the workload kit directory for this sandbox and returns its reference."""
    rendered = render(config, cwd)
    kit_dir = Path(rendered.ref.dir)
    kit_dir.mkdir(parents=True, exist_ok=True)
    for name, text in ((f"{WORKLOAD_KIT_NAME}.yaml", rendered.descriptor), (f"{WORKLOAD_KIT_NAME}.dockerfile", rendered.dockerfile)):
        target = kit_dir / name
        if not target.is_file() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
    return rendered.ref


def write_for_snapshot(config: AgyConfig, cwd: Path, dest_dir: Path) -> WorkloadRef:
    """
    Writes the workload kit without its setup_scripts install hook into `dest_dir`, for a
    `sbx create --template` that seeds the already-provisioned snapshot. The Dockerfile is
    identical to the normal workload; only the install hook is dropped. The normal workload
    kit directory (used by the saved plan and future upgrades) is left untouched.
    """
    source, _ = project_dockerfile(cwd)
    dockerfile = render_dockerfile(source.read_text(encoding="utf-8"), config.base_image)
    descriptor = descriptor_text(config, include_setup=False)
    dest_dir.mkdir(parents=True, exist_ok=True)
    for name, text in ((f"{WORKLOAD_KIT_NAME}.yaml", descriptor), (f"{WORKLOAD_KIT_NAME}.dockerfile", dockerfile)):
        (dest_dir / name).write_text(text, encoding="utf-8")
    return WorkloadRef(dir=str(dest_dir), fingerprint=fingerprint(descriptor, dockerfile))


def delete(sandbox_name: str) -> None:
    """Removes the generated kit directory of a sandbox that no longer exists."""
    shutil.rmtree(paths.workload_dir(sandbox_name), ignore_errors=True)
    try:
        paths.workload_dir(sandbox_name).parent.rmdir()
    except OSError:
        pass
